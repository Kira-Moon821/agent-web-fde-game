    ("什么是参考区间？", ["健康人群", "不等于患病"], ["超标就是病"]),
    ("什么是危急值？", ["危及生命", "立即通知"], ["第二天再看"]),
    ("激素为什么固定时间抽血？", ["昼夜节律", "横向比较"], []),
    ("轻度异常多久复查？", ["2-4 周", "趋势"], []),
    ("布洛芬和对乙酰氨基酚能一起吃吗？", ["医生评估", "出血"], ["随便叠加"]),
    ("eGFR 是怎么算出来的？", ["肌酐", "年龄"], []),
    ("血钾标本溶血会怎样？", ["假性升高", "复查"], []),
