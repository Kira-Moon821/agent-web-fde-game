    ("ALT 的参考区间是多少？", ["7-40", "U/L"], ["不需要再查其他"]),
    ("肌酐正常范围是多少？", ["57-97", "41-73"], ["一定是肾病"]),
    ("血钾危急值是多少？", ["6.0", "危急值"], ["自己补钾"]),
